# STEP 5: MODEL TRAINING------------------------------------------------------------------------------------------------
# Now that we have our base model finished, it's time to train our model. In order to do this,
# we'll seperate the data (16 for training, 4 for testing) and create a training loop. All 
# the previous code (besides the datasets) will be commented out for readability purposes.
# We begin by shuffling the student dataset, and then categorizing 80% for training and
# 20% for testing.

def sigmoid(z):
    """Convert scores into predicted probabilites of passing."""
    return 1 / (1 + np.exp(-z))

def binary_cross_entropy(y, p):
    """Calculate the average loss across students."""
    # Keep probabilities away from 0 and 1 to avoid log(0).
    p = np.clip(p, 1e-15, 1 - 1e-15)

    return -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))

# Shuffle student indices reproducibly
rng = np.random.default_rng(42)
indices = rng.permutation(len(X))

# Use 80% for training and 20% for testing
split = int(0.8 * len(X))

train_indices = indices[:split]
test_indices = indices[split:]

X_train = X[train_indices]
y_train = y[train_indices]

X_test = X[test_indices]
y_test = y[test_indices]

# Now, let's put our optimization function (gradient descent) into a training loop.
# Start training from zero
w = 0.0
b = 0.0

learning_rate = 0.01
epochs = 10000

for epoch in range(epochs):
    # Predict using the current parameters
    z = w * X_train + b
    probabilities = sigmoid(z)

    # Calculate gradients using only training data
    dw = np.mean((probabilities - y_train) * X_train)
    db = np.mean(probabilities - y_train)

    # Update both parameters
    w -= learning_rate * dw
    b -= learning_rate * db

    # Display progress every 1,000 updates
    if (epoch + 1) % 1000 == 0:
        updated_probabilities = sigmoid(w * X_train + b)
        loss = binary_cross_entropy(y_train, updated_probabilities)

        print(f"Epoch {epoch + 1}: loss = {loss:.4f}")

print("Final weight:", w)
print("Final bias:", b)

# Now that we have our training loop, let's evaluate our model on the four students that
# were held back for testing.

# Predict probabilities for the held-out students
test_probabilities = sigmoid(w * X_test + b)

# Convert probabilities into pass/fail predictions
test_predictions = (test_probabilities >= 0.5).astype(int)

# Compare the predictions with the actual outcomes
for hours, probability, prediction, actual in zip(X_test, test_probabilities, test_predictions, y_test):
    print(
        f"Hours: {hours:.1f} | "
        f"Pass probability: {probability:.1%} | "
        f"Predicted: {prediction} | "
        f"Actual: {actual}"
    )

# Calculate test loss and accuracy
test_loss = binary_cross_entropy(y_test, test_probabilities)
accuracy = np.mean(test_predictions == y_test)

print(f"\nTest loss: {test_loss:.4f}") # BCE loss checks how well the predicted probabilities match the outcomes
print(f"Test accuracy: {accuracy:.1%}") # Accuracy checks what fraction of pass/fail predictions are correct

