# close to 1. Whatever happens, we want a high outcome; high outcome -> higher likelihood -> low loss.
# This works pretty simple for a student passing; after all, our model generating
# 0.9 for a student passing is extremely close to the actual outcome of 1. However,
# if our model were to generate 0.9 for a student failing, this wouldn't apply. Thus,
# for scenarios where the student fails, we need to subtract the predicted probability
# from 1. If our model were to generate a 0.9 for a student failing, that is extremely
# far from our actual outcome of 0. Thus, 1 - 0.9 outputs 0.1, which means our prediction
